"use client";

import { useEffect, useState } from "react";
import { QrCode, X, Copy, Check, ExternalLink } from "lucide-react";

export default function SiteQrCode() {
  const [open, setOpen] = useState(false);
  const [url, setUrl] = useState("");
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    setUrl(`${window.location.origin}/#rides`);
  }, []);

  async function copyUrl() {
    if (!url) return;
    try {
      await navigator.clipboard.writeText(url);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1800);
    } catch {
      setCopied(false);
    }
  }

  const isLocal = url.includes("localhost") || url.includes("127.0.0.1");
  const qrImage = url
    ? `https://api.qrserver.com/v1/create-qr-code/?size=240x240&data=${encodeURIComponent(url)}`
    : "";

  return <>
    <button className="nav-cta qr-trigger" type="button" onClick={() => setOpen(true)}>
      <QrCode size={15} /> QR code
    </button>
    {open && <div className="qr-backdrop" role="presentation" onClick={() => setOpen(false)}>
      <section className="qr-dialog" role="dialog" aria-modal="true" aria-labelledby="qr-title" onClick={(event) => event.stopPropagation()}>
        <button className="qr-close" type="button" aria-label="Close QR code" onClick={() => setOpen(false)}><X size={18} /></button>
        <div className="qr-icon"><QrCode size={20} /></div>
        <h2 id="qr-title">Scan to visit LakerPool</h2>
        <p>Scan this code with your phone camera to open the ride planner.</p>
        {qrImage && <img className="qr-image" src={qrImage} alt="QR code linking to the LakerPool ride planner" width="240" height="240" />}
        {url && <a className="qr-url" href={url} target="_blank" rel="noreferrer"><span>{url}</span><ExternalLink size={14} /></a>}
        {isLocal && <p className="qr-warning">This address is local to your computer. For a phone on the same Wi-Fi, use your computer’s local network IP and port 3000; for access anywhere, deploy the site and use its public URL.</p>}
        <button className="qr-copy" type="button" onClick={copyUrl} disabled={!url}>{copied ? <Check size={15} /> : <Copy size={15} />}{copied ? "Copied" : "Copy link"}</button>
        <small className="qr-caption">QR image is generated by QRServer from the link shown above.</small>
      </section>
    </div>}
  </>;
}
